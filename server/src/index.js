import express from "express";
import cors from "cors";
import dotenv from "dotenv";
import mongoose from "mongoose";
import path from "path";
import {fileURLToPath} from "url";
import authRoutes from "./routes/auth.js";
import projectRoutes from "./routes/projects.js";
dotenv.config();
const app=express();
const __dirname=path.dirname(fileURLToPath(import.meta.url));
app.use(cors({origin:process.env.CLIENT_ORIGIN?.split(",")||true}));
app.use(express.json({limit:"2mb"}));
app.use("/uploads",express.static(path.resolve("uploads")));
app.get("/api/health",(req,res)=>res.json({status:"ok",service:"ZahidCodes Portfolio API"}));
app.use("/api/auth",authRoutes);
app.use("/api/projects",projectRoutes);
const port=process.env.PORT||5000;
if(process.env.MONGODB_URI){
 mongoose.connect(process.env.MONGODB_URI).then(()=>console.log("MongoDB connected")).catch(e=>console.error("MongoDB:",e.message));
}else console.warn("MONGODB_URI not set. Configure server/.env before using the CMS.");
app.listen(port,()=>console.log(`API running on ${port}`));
